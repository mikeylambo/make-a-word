import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';

// Exercise viewport/focus behavior without claiming real iOS keyboard coverage.
const source = fs.readFileSync(new URL('../src/mobile.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const classes = new Map();
const styles = new Map();
const events = {};
const attributes = new Map();
const input = { setAttribute: (key,value) => attributes.set(key,value) };
const root = { querySelectorAll: () => [input], addEventListener: (key,fn) => { events[key] = fn; } };
let callback;
const document = { activeElement:null, documentElement:{style:{setProperty:(key,value)=>styles.set(key,value)},classList:{toggle:(key,value)=>classes.set(key,value)}},addEventListener:(key,fn)=>{events[key]=fn;} };
const window = { innerHeight:844, visualViewport:{height:844,offsetTop:0,addEventListener:(key,fn)=>{events['viewport-'+key]=fn;}},addEventListener:(key,fn)=>{events[key]=fn;} };
const context = {exports:{},window,document,matchMedia:()=>({matches:true}),requestAnimationFrame:fn=>{callback=fn;return 1;},MutationObserver:class{observe(){} } };
vm.runInNewContext(compiled,context);
context.exports.installMobileExperience(root);
callback();
assert.equal(classes.get('keyboard-open'),false);
assert.equal(attributes.get('enterkeyhint'),'send');
assert.equal(attributes.get('autocorrect'),'off');
document.activeElement={matches:()=>true};
window.visualViewport.height=480;
events['viewport-resize'](); callback();
assert.equal(classes.get('keyboard-open'),true);
assert.equal(styles.get('--visible-height'),'480px');
let prevented=false;
events.pointerdown({target:{closest:()=>true},preventDefault:()=>{prevented=true;}});
assert.equal(prevented,true);
document.activeElement=null;
events.focusout(); callback();
assert.equal(classes.get('keyboard-open'),false);
window.visualViewport=undefined;
events.resize(); callback();
assert.equal(styles.get('--visible-height'),'844px');
console.log('Mobile runtime passed: keyboard open/close, viewport fallback, keyboard hints, and submit focus preservation.');
